package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// OrgProfile maps a QFabric organization onto the Fabric test network.
//
//	OrgA (Manufacturer) -> Org1MSP, peer0.org1.example.com:7051
//	OrgB (Supplier)     -> Org2MSP, peer0.org2.example.com:9051
type OrgProfile struct {
	OrgID        string
	DisplayName  string
	Role         string
	MSPID        string
	Domain       string // org1.example.com
	PeerEndpoint string // dns:///localhost:7051
	GatewayPeer  string // TLS server name override
}

var orgProfiles = map[string]OrgProfile{
	"OrgA": {"OrgA", "Manufacturer", "MANUFACTURER", "Org1MSP", "org1.example.com", "dns:///localhost:7051", "peer0.org1.example.com"},
	"OrgB": {"OrgB", "Supplier", "SUPPLIER", "Org2MSP", "org2.example.com", "dns:///localhost:9051", "peer0.org2.example.com"},
}

// Config is read from environment variables (see blockchain/.env.example).
type Config struct {
	Org            OrgProfile
	TestNetworkDir string // fabric-samples/test-network
	ChannelName    string
	ChaincodeName  string
	CryptoAPIURL   string
}

func loadConfig() (*Config, error) {
	orgID := env("QFABRIC_ORG", "OrgA")
	profile, ok := orgProfiles[orgID]
	if !ok {
		return nil, fmt.Errorf("QFABRIC_ORG must be OrgA or OrgB, got %q", orgID)
	}
	return &Config{
		Org:            profile,
		TestNetworkDir: env("QFABRIC_TEST_NETWORK_DIR", filepath.Join("network", "fabric-samples", "test-network")),
		ChannelName:    env("QFABRIC_CHANNEL", "mychannel"),
		ChaincodeName:  env("QFABRIC_CHAINCODE", "qfabric-audit"),
		CryptoAPIURL:   env("QFABRIC_CRYPTO_API_URL", "http://localhost:8000/api/v1"),
	}, nil
}

// User1 credentials and peer TLS CA generated by the test network.
func (c *Config) userMSPDir() string {
	return filepath.Join(c.TestNetworkDir, "organizations", "peerOrganizations", c.Org.Domain,
		"users", "User1@"+c.Org.Domain, "msp")
}

func (c *Config) certDir() string { return filepath.Join(c.userMSPDir(), "signcerts") }
func (c *Config) keyDir() string  { return filepath.Join(c.userMSPDir(), "keystore") }

func (c *Config) tlsCertPath() string {
	return filepath.Join(c.TestNetworkDir, "organizations", "peerOrganizations", c.Org.Domain,
		"peers", c.Org.GatewayPeer, "tls", "ca.crt")
}

func env(key, fallback string) string {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		return v
	}
	return fallback
}
